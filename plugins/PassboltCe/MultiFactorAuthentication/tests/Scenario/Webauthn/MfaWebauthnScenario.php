namespace Passbolt\MultiFactorAuthentication\Test\Scenario\Webauthn;

use App\Test\Factory\UserFactory;
use Cake\I18n\DateTime;
use CakephpFixtureFactories\Scenario\FixtureScenarioInterface;
use CakephpFixtureFactories\Scenario\ScenarioAwareTrait;
use Passbolt\MultiFactorAuthentication\Test\Factory\MfaAccountSettingFactory;
use Passbolt\MultiFactorAuthentication\Test\Factory\MfaWebauthnCredentialFactory;
use Passbolt\MultiFactorAuthentication\Utility\MfaAccountSettings;
use Passbolt\MultiFactorAuthentication\Utility\MfaSettings;

class MfaWebauthnScenario implements FixtureScenarioInterface
{
    use ScenarioAwareTrait;

    /**
     * @param mixed ...$args `$args[0]`: user (autogenerated when null). `$args[1]`: bool, org enabled (default true).
     * @return array{0: \App\Model\Entity\User, 1: \App\Model\Entity\WebauthnCredential}
     */
    public function load(...$args): array
    {
        /** @var \App\Model\Entity\User $user */
        $user = $args[0] ?? UserFactory::make()->user()->persist();
        $isSupported = $args[1] ?? true;

        $this->loadFixtureScenario(MfaWebauthnOrganizationOnlyScenario::class, $isSupported);

        $credential = MfaWebauthnCredentialFactory::make()->withUser($user)->persist();
        MfaAccountSettingFactory::make()
            ->setField('user_id', $user->id)
            ->patchData([
                'value' => json_encode([
                    MfaSettings::PROVIDERS => [MfaSettings::PROVIDER_WEBAUTHN],
                    MfaSettings::PROVIDER_WEBAUTHN => [
                        MfaAccountSettings::VERIFIED => DateTime::now()->toIso8601String(),
                    ],
                ]),
            ])
            ->persist();

        return [$user, $credential];
    }
}
